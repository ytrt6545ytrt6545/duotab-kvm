/**
 * 將 Android KeyCode 轉換為 Windows VK 虛擬鍵碼
 * @param {number} androidKeyCode
 * @returns {number} Windows VK Code，若無直接映射則返回 0
 */
export function androidToWindowsVk(androidKeyCode) {
  return ANDROID_TO_WINDOWS_MAP.get(androidKeyCode) || 0;
}

/**
 * 將 Android MotionEvent 按鈕遮罩轉換為 DuoTab Windows 按鈕遮罩
 * Android: BUTTON_PRIMARY=1, BUTTON_SECONDARY=2, BUTTON_TERTIARY=4, BUTTON_BACK=8, BUTTON_FORWARD=16
 */
export function androidButtonsToWindows(androidButtonState) {
  let buttons = BUTTON_MASKS.NONE;
  if (androidButtonState & 1) buttons |= BUTTON_MASKS.LEFT;
  if (androidButtonState & 2) buttons |= BUTTON_MASKS.RIGHT;
  if (androidButtonState & 4) buttons |= BUTTON_MASKS.MIDDLE;
  if (androidButtonState & 8) buttons |= BUTTON_MASKS.BACK;
  if (androidButtonState & 16) buttons |= BUTTON_MASKS.FORWARD;
  return buttons;
}

/**
 * 將 Android MetaState 轉換為修飾鍵遮罩 (Modifier Masks)
 * Android: META_SHIFT_ON=1, META_ALT_ON=2, META_SYM_ON=4, META_CTRL_ON=4096, META_META_ON=65536
 */
export function androidMetaStateToModifiers(metaState) {
  let mods = MODIFIER_MASKS.NONE;
  // Shift: 0x01 (META_SHIFT_ON) | 0x40 (META_SHIFT_LEFT_ON) | 0x80 (META_SHIFT_RIGHT_ON)
  if (metaState & 0xC1) mods |= MODIFIER_MASKS.SHIFT;
  // Ctrl: 0x1000 (META_CTRL_ON) | 0x2000 (META_CTRL_LEFT_ON) | 0x4000 (META_CTRL_RIGHT_ON)
  if (metaState & 0x7000) mods |= MODIFIER_MASKS.CTRL;
  // Alt: 0x02 (META_ALT_ON) | 0x10 (META_ALT_LEFT_ON) | 0x20 (META_ALT_RIGHT_ON)
  if (metaState & 0x32) mods |= MODIFIER_MASKS.ALT;
  // Meta/Win: 0x10000 (META_META_ON) | 0x20000 (META_META_LEFT_ON) | 0x40000 (META_META_RIGHT_ON)
  if (metaState & 0x70000) mods |= MODIFIER_MASKS.META_WIN;
  return mods;
}
